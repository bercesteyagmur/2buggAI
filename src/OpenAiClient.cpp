OpenAIClient::OpenAIClient() {
    const LlmConfig legacy = LlmProvider::legacyConfig();
    report_ = LlmProvider("Report", legacy);
    fixer_  = LlmProvider("Fix", legacy);

    pipeline_ = LlmProvider::pipelineEnabled();
    if (pipeline_) {
        debugger_ = LlmProvider("Debugger", LlmProvider::roleConfig("Debugger"));
        reviewer_ = LlmProvider("Reviewer", LlmProvider::roleConfig("Reviewer"));
        verifier_ = LlmProvider("Verifier", LlmProvider::roleConfig("Verifier"));
    }
}

OpenAIResult OpenAIClient::debug_report(const std::string& report_json) const {
    const std::string instructions =
        "You are a Senior Debugger. Analyze the JSON (debugger output, runtime errors, "
        "Valgrind output if available, detected errors). "
        "Structure your response in Markdown with the following sections:\n\n"
        "## Summary\n"
        "A brief summary of the main issue (max 2 sentences).\n\n"
        "## Severity\n"
        "critical, high, medium, or low\n\n"
        "## Bugs\n"
        "For each bug:\n\n"
        "### Bug N: [Title]\n"
        "- **File:** path/to/file.ext:line\n"
        "- **Category:** Choose the most specific category name "
        "(e.g., memory_leak, null_pointer, uninitialized_variable, "
        "off_by_one, integer_overflow, etc.). Use snake_case.\n"
        "- **Language:** general / c / cpp / java / python / php / javascript / typescript / vue / sql. "
        "Use 'general' if the bug can occur in multiple languages "
        "(e.g., logic errors, off-by-one). Use a specific language "
        "only if the bug is unique to that language's syntax or runtime "
        "(e.g., NullPointerException is java-specific, missing semicolon "
        "is general).\n"
        "- **Problem:** What is the problem (brief description)\n\n"
        "**Buggy code:**\n"
        "```\n"
        "// Original buggy code — use the language of the analyzed file "
        "(c, cpp, java, python, php, javascript, typescript, vue, sql)\n"
        "```\n\n"
        "**Fixed code:**\n"
        "```\n"
        "// Corrected code in the same language\n"
        "```\n\n"
        "**Explanation:** Brief explanation of why the fix works.\n\n"
        "## Recommendations (only if needed)\n"
        "OMIT THIS SECTION ENTIRELY unless there is at least one concrete, "
        "non-trivial systemic recommendation (tooling, build flags, testing "
        "strategy, language-specific best practices). "
        "Do NOT include generic advice like 'write tests' or 'use a linter'.\n\n"
        "Respond in English.";

    const std::string input =
        "Here is the report as JSON:\n\n" + report_json +
        "\n\nPlease analyze and explain the error, then propose a fix.";

    LlmResponse resp = report_.chat(instructions, input, REPORT_MAX_TOKENS);

    OpenAIResult out;
    out.http_status = resp.http_status;
    out.raw_json = resp.raw_json.empty() ? resp.error : resp.raw_json;
    out.text = resp.text;
    if (!resp.ok) {
        std::cerr << "[Report " << report_.label() << "] " << resp.error << "\n";
    }
    return out;
}

FixResult OpenAIClient::fix_code(const FixRequest& req) const {
    try {
        return pipeline_ ? fix_code_pipeline(req) : fix_code_single(req);
    } catch (const std::exception& e) {
        std::cout << "  [fix_code] Fehler: " << e.what() << "\n";
        return FixResult{};
    }
}

FixResult OpenAIClient::fix_code_single(const FixRequest& req) const {
    FixResult result;
    const std::string tag = "[Fix " + fixer_.label() + "]";

    LlmResponse resp = fixer_.chat(FIX_INSTRUCTIONS, fix_input(req), DEBUGGER_MAX_TOKENS);
    if (!resp.ok) {
        std::cout << "  " << tag << " " << resp.error << "\n";
        return result;
    }

    const RequestFile* target = nullptr;
    if (!parse_fix(resp.text, request_files(req.source_code), tag, result, target)) {
        return FixResult{};
    }
    return result;
}

FixResult OpenAIClient::fix_code_pipeline(const FixRequest& req) const {
    const std::vector<RequestFile> files = request_files(req.source_code);
    const std::string fixInput = fix_input(req);

    // ---------- 1. Debugger ----------
    const std::string dbgTag = "[Debugger " + debugger_.label() + "]";
    LlmResponse resp = debugger_.chat(FIX_INSTRUCTIONS, fixInput, DEBUGGER_MAX_TOKENS);
    if (!resp.ok) {
        std::cout << "  " << dbgTag << " " << resp.error << "\n";
        return FixResult{};
    }

    FixResult fix;
    const RequestFile* target = nullptr;
    if (!parse_fix(resp.text, files, dbgTag, fix, target)) return FixResult{};
    if (!fix.success) {
        std::cout << "  " << dbgTag << " meldet success=false – kein Fix\n";
        return FixResult{};
    }
    std::cout << "  " << dbgTag << " Fix für " << fix.file_path << "\n";

    std::string diff = unified_diff(target->content, fix.fixed_code, target->path);
    if (diff.empty()) {
        std::cout << "  [Debugger] Fix ändert nichts am Code – Versuch verworfen\n";
        return FixResult{};
    }

    // ---------- 2. Reviewer ----------
    const std::string revTag = "[Reviewer " + reviewer_.label() + "]";
    resp = reviewer_.chat(REVIEWER_INSTRUCTIONS, review_input(req, *target, diff), REVIEW_MAX_TOKENS);
    if (!resp.ok) {
        std::cout << "  " << revTag << " " << resp.error << "\n";
        return FixResult{};
    }
    Review review = parse_review(resp.text);
    if (!review.valid) {
        std::cout << "  " << revTag << " Ungültiges JSON in der Antwort – Versuch verworfen\n";
        return FixResult{};
    }
    print_review(revTag, review);

    // ---------- 2b. Eine Überarbeitung bei CHANGES_REQUESTED ----------
    if (review.verdict == "CHANGES_REQUESTED") {
        std::cout << "  [Debugger] Überarbeitung\n";

        const std::string revisionInput = fixInput +
            "\n\n===== REVIEW OF YOUR PREVIOUS FIX =====\n"
            "A code reviewer requested changes to your previous fix. Your previous change "
            "(unified diff, generated by the tool) was:\n" + diff + "\n"
            "Reviewer findings:\n" + review.findings.dump(2) + "\n\n"
            "Reviewer summary: " + review.summary + "\n\n"
            "Your previous change was NOT applied. Start again from the original source code "
            "shown above, address the findings and return the complete content of the file "
            "in the same JSON format as before.";

        resp = debugger_.chat(FIX_INSTRUCTIONS, revisionInput, DEBUGGER_MAX_TOKENS);
        if (!resp.ok) {
            std::cout << "  [Debugger] " << resp.error << "\n";
            return FixResult{};
        }
        if (!parse_fix(resp.text, files, "[Debugger]", fix, target)) return FixResult{};
        if (!fix.success) {
            std::cout << "  [Debugger] meldet success=false – kein Fix\n";
            return FixResult{};
        }

        diff = unified_diff(target->content, fix.fixed_code, target->path);
        if (diff.empty()) {
            std::cout << "  [Debugger] Überarbeitung ändert nichts am Code – Versuch verworfen\n";
            return FixResult{};
        }

        resp = reviewer_.chat(REVIEWER_INSTRUCTIONS, review_input(req, *target, diff), REVIEW_MAX_TOKENS);
        if (!resp.ok) {
            std::cout << "  [Reviewer] " << resp.error << "\n";
            return FixResult{};
        }
        review = parse_review(resp.text);
        if (!review.valid) {
            std::cout << "  [Reviewer] Ungültiges JSON in der Antwort – Versuch verworfen\n";
            return FixResult{};
        }
        print_review("[Reviewer]", review);
        if (review.verdict == "CHANGES_REQUESTED") {
            std::cout << "  [Reviewer] weiterhin CHANGES_REQUESTED – Verifier entscheidet\n";
        }
    }

    // ---------- 3. Verifier ----------
    const std::string verTag = "[Verifier " + verifier_.label() + "]";
    const json reviewJson = {
        {"verdict", review.verdict}, {"findings", review.findings}, {"summary", review.summary}
    };
    const std::string verifyInput =
        "Error name: " + req.error_name + "\n\n"
        "Language: " + req.language + "\n\n"
        "Error output:\n" + clip(req.error_output, AGENT_OUTPUT_LIMIT) + "\n\n"
        "Final change to " + target->path + " (unified diff, generated by the tool):\n" + diff + "\n"
        "Code review:\n" + reviewJson.dump(2) + "\n\n"
        "Please verify and return ONLY the JSON object as specified.";

    resp = verifier_.chat(VERIFIER_INSTRUCTIONS, verifyInput, REVIEW_MAX_TOKENS);
    if (!resp.ok) {
        std::cout << "  " << verTag << " " << resp.error << "\n";
        return FixResult{};
    }
    json verdict = parse_agent_json(resp.text);
    if (verdict.is_null() || !verdict.contains("confirmed") || !verdict["confirmed"].is_boolean()) {
        std::cout << "  " << verTag << " Ungültiges JSON in der Antwort – Versuch verworfen\n";
        return FixResult{};
    }

    if (!verdict["confirmed"].get<bool>()) {
        std::cout << "  " << verTag << " abgelehnt: " << json_string(verdict, "reason") << "\n";
        if (verdict.contains("remaining_issues") && verdict["remaining_issues"].is_array())
            for (const auto& issue : verdict["remaining_issues"])
                if (issue.is_string()) std::cout << "      - " << issue.get<std::string>() << "\n";
        return FixResult{};
    }

    std::cout << "  " << verTag << " bestätigt\n";
    fix.success = true;
    return fix;
}
