std::string fix_input(const FixRequest& req) {
    return
        "Error name: " + req.error_name + "\n\n"
        "Language: " + req.language + "\n\n"
        "Error output:\n" + req.error_output + "\n\n"
        "Source code:\n" + req.source_code + "\n\n"
        "Checklist:\n" + req.checklist + "\n\n"
        "Please analyze and return ONLY the JSON object as specified.";
}

std::string clip(const std::string& s, size_t max) {
    return s.size() <= max ? s : s.substr(0, max) + "\n... [truncated]";
}

std::string json_string(const json& j, const char* key) {
    return (j.contains(key) && j[key].is_string()) ? j[key].get<std::string>() : std::string();
}

bool json_bool(const json& j, const char* key) {
    return j.contains(key) && j[key].is_boolean() && j[key].get<bool>();
}

json parse_agent_json(const std::string& text) {
    json j = json::parse(extract_json_object(text), nullptr, false);
    return (j.is_discarded() || !j.is_object()) ? json() : j;
}

// ---------- Dateien aus dem Request ("===== FILE: <pfad> =====") ----------

struct RequestFile {
    std::string path;
    std::string content;
};

std::vector<RequestFile> request_files(const std::string& source) {
    static const std::string head = "===== FILE: ";
    static const std::string tail = " =====";

    std::vector<RequestFile> files;
    size_t contentStart = std::string::npos;
    size_t pos = 0;

    auto close = [&](size_t end) {
        if (files.empty() || contentStart == std::string::npos) return;
        std::string content = source.substr(contentStart, end - contentStart);
        // main.cpp / WebPipeline hängen "\n\n" an jeden Dateiinhalt an
        if (content.size() >= 2 && content.compare(content.size() - 2, 2, "\n\n") == 0)
            content.resize(content.size() - 2);
        files.back().content = content;
    };

    while (pos < source.size()) {
        size_t eol = source.find('\n', pos);
        if (eol == std::string::npos) eol = source.size();
        const std::string line = source.substr(pos, eol - pos);

        if (line.size() > head.size() + tail.size() &&
            line.compare(0, head.size(), head) == 0 &&
            line.compare(line.size() - tail.size(), tail.size(), tail) == 0) {
            close(pos);
            files.push_back({line.substr(head.size(), line.size() - head.size() - tail.size()), ""});
            contentStart = std::min(eol + 1, source.size());
        }
        pos = eol + 1;
    }
    close(source.size());
    return files;
}

const RequestFile* find_request_file(const std::vector<RequestFile>& files, const std::string& path) {
    namespace fs = std::filesystem;
    if (path.empty()) return nullptr;
    const std::string normal = fs::path(path).lexically_normal().string();
    for (const auto& f : files) {
        if (f.path == path || fs::path(f.path).lexically_normal().string() == normal) return &f;
    }
    return nullptr;
}

// Antwort des Debuggers in ein FixResult übersetzen. Nur Pfade aus dem Request
// werden akzeptiert; alles andere wird verworfen. Gibt false bei ungültiger Antwort.
bool parse_fix(const std::string& text, const std::vector<RequestFile>& files,
               const std::string& tag, FixResult& out, const RequestFile*& target) {
    json j = parse_agent_json(text);
    if (j.is_null()) {
        std::cout << "  " << tag << " Ungültiges JSON in der Antwort – Versuch verworfen\n";
        return false;
    }

    out = FixResult{};
    out.fixed_code   = json_string(j, "fixed_code");
    out.file_path    = json_string(j, "file_path");
    out.success      = json_bool(j, "success");
    out.is_confident = json_bool(j, "is_confident");
    if (j.contains("new_errors") && j["new_errors"].is_array())
        for (const auto& e : j["new_errors"])
            if (e.is_string()) out.new_errors.push_back(e.get<std::string>());

    target = find_request_file(files, out.file_path);
    if (!target) {
        std::cout << "  " << tag << " Verworfen: Pfad '" << out.file_path
                  << "' war nicht Teil des Requests\n";
        return false;
    }
    out.file_path = target->path;

    if (out.fixed_code.empty()) {
        std::cout << "  " << tag << " Leerer fixed_code – Versuch verworfen\n";
        return false;
    }
    return true;
}

struct Review {
    bool valid = false;
    std::string verdict;
    json findings = json::array();
    std::string summary;
};

Review parse_review(const std::string& text) {
    Review r;
    json j = parse_agent_json(text);
    if (j.is_null()) return r;

    r.verdict = json_string(j, "verdict");
    for (char& c : r.verdict) c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    if (r.verdict != "APPROVE" && r.verdict != "CHANGES_REQUESTED") return r;

    if (j.contains("findings") && j["findings"].is_array()) r.findings = j["findings"];
    r.summary = json_string(j, "summary");
    r.valid = true;
    return r;
}

void print_review(const std::string& tag, const Review& r) {
    std::cout << "  " << tag << " " << r.verdict;
    if (!r.findings.empty()) std::cout << " (" << r.findings.size() << " Findings)";
    std::cout << "\n";
    for (const auto& f : r.findings) {
        if (!f.is_object()) continue;
        std::cout << "      - [" << json_string(f, "severity") << "] "
                  << json_string(f, "file") << ": " << json_string(f, "problem") << "\n";
    }
}

std::string review_input(const FixRequest& req, const RequestFile& file, const std::string& diff) {
    return
        "Error name: " + req.error_name + "\n\n"
        "Language: " + req.language + "\n\n"
        "Error output:\n" + clip(req.error_output, AGENT_OUTPUT_LIMIT) + "\n\n"
        "Original source of " + file.path + ":\n" + file.content + "\n\n"
        "Proposed change (unified diff, generated by the tool):\n" + diff + "\n"
        "Please review and return ONLY the JSON object as specified.";
}

